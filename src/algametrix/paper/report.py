def harmonization(a, b, conclusion_lines, registry, definition=None) -> str:
    lines = header(
        "COST HARMONIZATION",
        "two formally separate analyses, each on a cohort that does not change "
        "between its own stages",
    )

    lines += [
        "READ THIS FIRST",
        THIN,
        "  Analysis A and Analysis B are NOT two steps of one chain. A measures the",
        "  effect of currency and price-year conversion over the full eligible literature",
        "  cohort. B measures the effect of imposing a common accounting profile over the",
        "  much smaller cohort the engine can execute. The spread in A and the spread in B",
        "  describe different populations and must never be quoted as a sequence.",
        "",
    ]

    # ---------------- Analysis A ----------------
    from .endpoints import PRIMARY_COHORT_LABEL

    lines += [RULE, "FULL LITERATURE COHORT (Analysis A)", RULE,
              f"  cohort n = {len(a.cohort)}; identical at stage A1 and A2",
              f"  what it is: {PRIMARY_COHORT_LABEL}",
              f"  members  : {', '.join(a.cohort.ids)}", ""]
    if definition is not None:
        for s in definition.statement():
            lines.append(f"  {s}")
        lines.append("")
    lines.append(format_spread(a.stage_common_currency, "EUR/kg"))
    lines.append("")
    lines.append(format_spread(a.stage_price_normalized, "EUR/kg"))
    lines.append("")
    lines += ["  ROBUSTNESS TO THE COST SPLIT", THIN,
              "  No study in the cohort publishes a CAPEX/OPEX breakdown, so the split used",
              "  to weight the per-class indices is taken from the engine's own executable",
              "  reconstructions and the result is reported as an interval over them."]
    if a.shares is not None:
        lines += a.shares.as_lines()
    lines.append("")
    for key in ("lower", "upper", "legacy"):
        lines.append(format_spread(a.bounds_spreads[key], "EUR/kg"))
        lines.append("")

    lines += ["  PER-STUDY TRANSFORMATION AUDIT", THIN]
    for sid in a.cohort.ids:
        n = a.normalizations[sid]
        lines.append(
            f"    {sid:26s} {fmt(n.source_value):>10s} {fmt(n.source_currency)} "
            f"{fmt(n.source_price_year)}  ->  {n.value:,.4g} "
            f"{n.target_currency} {n.target_price_year}"
        )
        lines += n.audit_lines()
    lines.append("")

    if a.excluded:
        lines += ["  EXCLUDED FROM THIS COHORT", THIN]
        for sid, reason in a.excluded:
            lines.append(f"    {sid:26s} {reason}")
        lines.append("")

    # ---------------- Analysis B ----------------
    from .harmonization import independence_audit

    lines += [RULE, "MATCHED RECONSTRUCTABLE COHORT (Analysis B)", RULE,
              f"  cohort n = {b.n}; identical at stages B1, B2 and B3",
              f"  members  : {', '.join(b.cohort.ids) if b.n else '(none)'}", ""]
    if b.n:
        ind = independence_audit(b.cohort)
        lines += ["  INDEPENDENCE OF THE EVIDENCE", THIN,
                  f"    records          : {ind.n}",
                  f"    publications     : {ind.n_publications}",
                  f"    external to us   : {ind.n_external}",
                  f"    authors' own     : {', '.join(ind.self_cited) or 'none'}",
                  f"    overlap unknown  : {', '.join(ind.overlap_unknown) or 'none'}"]
        for doi, ids in sorted(ind.publications.items()):
            lines.append(f"      {doi:44s} {', '.join(ids)}")
        for s in ind.statement():
            lines.append(f"    {s}")
        lines.append("")
    if b.blocked:
        lines += ["  BLOCKED - declared Tier B, eligible on endpoint, but not executable:"]
        for sid, why in sorted(b.blocked.items()):
            lines.append(f"    {sid:26s} {why}")
        lines.append("")
    if b.basis_blocked:
        lines += ["  DROPPED - executable, but the engine output cannot be expressed in the",
                  "  common basis, so pooling it would repeat the currency-mixing defect:"]
        for sid, why in sorted(b.basis_blocked.items()):
            lines.append(f"    {sid:26s} {why}")
        lines.append("")
    lines += ["  COMMON ACCOUNTING PROFILE"] + b.profile.as_lines() + [""]

    if b.engine_transfers:
        lines += [
            "  PRICE BASIS OF THE ENGINE OUTPUTS",
            THIN,
            "    The engine returns a cost in the units of the price set it was fed. Stages",
            "    B2 and B3 are therefore transformed to the common basis before pooling; "
            "    without this the spread would mix currencies and price years.",
            f"    {'study_id':26s} {'engine basis':16s} {'kind':26s} transformation",
        ]
        for sid in b.cohort.ids:
            tr = b.engine_transfers.get(sid)
            if tr is None:
                continue
            lines.append(
                f"    {sid:26s} {tr.from_basis.label:16s} {tr.from_basis.kind:26s} "
                f"{tr.quality}"
                + (f" (x{tr.amount_out / tr.amount_in:.4f})"
                   if tr.amount_in and not tr.is_identity else "")
            )
            if tr.from_basis.is_mixed:
                lines.append(
                    f"      {'':24s} MIXED price set: "
                    f"{len(tr.from_basis.library_priced)} price(s) left at the shipped "
                    "library default, so this value is not purely in the declared currency"
                )
        lines.append("")

    if b.n:
        for sp in (b.stage_source_value, b.stage_source_accounting, b.stage_common_accounting):
            lines.append(format_spread(sp, "EUR/kg"))
            lines.append("")
        lines += ["  PAIRED STUDY-LEVEL CHANGE, source accounting -> common accounting", THIN,
                  f"    {'study_id':26s} {'source acc.':>12s} {'common acc.':>12s} "
                  f"{'abs':>10s} {'rel':>8s}"]
        for p in b.paired:
            rel = f"{p.relative:+.1%}" if p.relative is not None else "n/a"
            lines.append(
                f"    {p.study_id:26s} {p.before:12,.4g} {p.after:12,.4g} "
                f"{p.absolute:+10,.4g} {rel:>8s}"
            )
        lines.append("")
    else:
        lines += ["  No study in the dataset is both endpoint-eligible and executable.",
                  "  Analysis B cannot be run.", ""]

    lines += [RULE, "CONCLUSION (auto-generated, conditional)", RULE]
    for c in conclusion_lines:
        lines.append("  " + c)
    lines.append("")

    lines += ["INDEX PROVENANCE", THIN]
    for name, idx in sorted(registry.indices.items()):
        lines.append(
            f"  {name:22s} class={idx.normalization_class:14s} "
            f"available={'yes' if idx.available else 'NO':3s} "
            f"provenance={idx.provenance}"
        )
        if idx.source:
            lines.append(f"    source: {idx.source}")
        lines.append(f"    retrieval_date: {fmt(idx.retrieval_date)}")
        for t in idx.todos:
            lines.append(f"    TODO: {t}")
    lines.append("")
    return "\n".join(lines)


