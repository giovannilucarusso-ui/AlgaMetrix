def carbon_accounting(reports, spreads) -> str:
    from .carbon import format_carbon_report

    lines = header(
        "BIOGENIC-CARBON ACCOUNTING",
        "gross GWP, carbon flows and net GWP under every convention, for every "
        "executable scenario",
    )
    lines += [
        "CONVENTIONS",
        THIN,
        "  no_biogenic_credit              no adjustment; gross == net",
        "  source_specific_credit          credit CO2-fed carbon only (engine default;",
        "                                  credits carbon fixed by the GROSS biomass)",
        "  temporary_storage_credit_at_gate credit the carbon that leaves the gate in the",
        "                                  product, whatever fed it",
        "",
    ]
    for r in reports:
        lines.append(format_carbon_report(r))
        lines.append("")

    lines += [RULE, "SPREAD STATISTICS UNDER EACH CONVENTION", RULE,
              "  Ratios are never computed across zero: see each block's ratio convention.",
              ""]
    for sp in spreads:
        lines.append(format_spread(sp, "kg CO2-eq/kg"))
        lines.append("")
    return "\n".join(lines)


