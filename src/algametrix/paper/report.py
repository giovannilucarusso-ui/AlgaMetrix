def sobol_validation(outcomes, salib_present: bool, tolerance: float,
                     group_outcomes=None) -> str:
    lines = header(
        "SOBOL IMPLEMENTATION VALIDATION",
        "synthetic benchmarks with analytical indices, plus an independent "
        "reference implementation",
        seed=outcomes[0].seed if outcomes else None,
    )
    lines += [
        "ESTIMATORS",
        THIN,
        "  S_i  = (1/N) sum f(B)[f(AB_i) - f(A)] / Var(Y)      Saltelli et al. 2010",
        "  ST_i = (1/2N) sum [f(A) - f(AB_i)]^2 / Var(Y)       Jansen",
        "  A and B: two halves of one scrambled Sobol' sequence in 2k dimensions.",
        "  Var(Y) over the pooled A and B outputs. N(k+2) evaluations.",
        "",
        "  The GROUP estimator (sobol.analyze_groups) is the same pair of formulas with a",
        "  whole block of columns swapped at a time, so S[G] = Var(E[Y|X_G])/Var(Y). It is",
        "  validated separately below, because its headline quantity - the remainder, i.e.",
        "  the variance carried by interactions BETWEEN groups - has no per-parameter",
        "  analogue and cannot be checked by the benchmarks above.",
        "",
        f"  reference library available: {'SALib' if salib_present else 'NO (not installed)'}",
        "  reproduce the cross-check with:  pip install SALib && python reproduce.py --only sobol",
        f"  documented tolerance on analytical indices: {tolerance:g} absolute",
        "",
    ]
    all_ok = True
    for o in outcomes:
        lines += [THIN, f"BENCHMARK: {o.benchmark}   N={o.n_base}  "
                        f"evaluations={o.result.n_evaluations}  seed={o.seed}", THIN]
        ref = o.reference
        has_ref = bool(ref) and "S1" in (ref or {})
        head = (f"  {'param':6s} {'S1 exact':>10s} {'S1 algam.':>10s} "
                f"{'S1 95% CI':>20s} {'S1 |err|':>9s}")
        if has_ref:
            head += f" {'S1 SALib':>10s}"
        lines.append(head)
        for i, name in enumerate(o.parameters):
            e = o.result.s1[i]
            row = (f"  {name:6s} {o.s1_exact[i]:10.4f} {e.value:10.4f} "
                   f"[{e.ci_low:+8.4f},{e.ci_high:+8.4f}] {o.s1_abs_error[i]:9.4f}")
            if has_ref:
                row += f" {ref['S1'][i]:10.4f}"
            lines.append(row)
        head = (f"  {'param':6s} {'ST exact':>10s} {'ST algam.':>10s} "
                f"{'ST 95% CI':>20s} {'ST |err|':>9s}")
        if has_ref:
            head += f" {'ST SALib':>10s}"
        lines.append(head)
        for i, name in enumerate(o.parameters):
            e = o.result.st[i]
            row = (f"  {name:6s} {o.st_exact[i]:10.4f} {e.value:10.4f} "
                   f"[{e.ci_low:+8.4f},{e.ci_high:+8.4f}] {o.st_abs_error[i]:9.4f}")
            if has_ref:
                row += f" {ref['ST'][i]:10.4f}"
            lines.append(row)
        ok = o.max_abs_error <= tolerance and not o.result.violations()
        all_ok = all_ok and ok
        lines += [f"  max absolute error : {o.max_abs_error:.4f}  -> "
                  f"{'PASS' if ok else 'FAIL'}",
                  f"  index violations   : {o.result.violations() or 'none'}",
                  f"  dropped rows       : {o.result.dropped_rows}",
                  f"  runtime            : {o.result.runtime_s:.2f} s", ""]
        if ref and "error" in ref:
            lines.append(f"  reference library error: {ref['error']}")
            lines.append("")

    for o in group_outcomes or []:
        lines += [
            THIN,
            f"GROUP BENCHMARK: {o.benchmark}   N={o.n_base}  "
            f"evaluations={o.result.n_evaluations}  seed={o.seed}",
            THIN,
            f"  {o.description}",
            "  partition: " + "; ".join(f"{g} = {{{', '.join(o.members[g])}}}"
                                        for g in o.groups),
            "",
            f"  {'group':6s} {'S exact':>10s} {'S algam.':>10s} "
            f"{'S 95% CI':>20s} {'S |err|':>9s}",
        ]
        for i, g in enumerate(o.groups):
            e = o.result.s[i]
            lines.append(f"  {g:6s} {o.s_exact[i]:10.4f} {e.value:10.4f} "
                         f"[{e.ci_low:+8.4f},{e.ci_high:+8.4f}] {o.s_abs_error[i]:9.4f}")
        lines.append(f"  {'group':6s} {'ST exact':>10s} {'ST algam.':>10s} "
                     f"{'ST 95% CI':>20s} {'ST |err|':>9s}")
        for i, g in enumerate(o.groups):
            e = o.result.st[i]
            lines.append(f"  {g:6s} {o.st_exact[i]:10.4f} {e.value:10.4f} "
                         f"[{e.ci_low:+8.4f},{e.ci_high:+8.4f}] {o.st_abs_error[i]:9.4f}")
        # The remainder is the quantity the group decomposition reports and the
        # only one with no per-parameter analogue, so it is checked explicitly.
        lines.append(f"  {'rest':6s} {o.interactions_exact:10.4f} "
                     f"{o.result.interactions:10.4f} {'':20s} "
                     f"{o.interactions_abs_error:9.4f}   "
                     "(variance carried by interactions BETWEEN groups)")
        ok = o.max_abs_error <= tolerance and not o.result.violations()
        all_ok = all_ok and ok
        lines += [f"  max absolute error : {o.max_abs_error:.4f}  -> "
                  f"{'PASS' if ok else 'FAIL'}",
                  f"  index violations   : {o.result.violations() or 'none'}",
                  f"  dropped rows       : {o.result.dropped_rows}",
                  f"  runtime            : {o.result.runtime_s:.2f} s", ""]

    lines += [RULE, f"OVERALL: {'PASS' if all_ok else 'FAIL'}", RULE, ""]
    return "\n".join(lines)


def sobol_convergence(blocks, criteria: dict) -> str:
    lines = header("SOBOL CONVERGENCE", "smallest sample size meeting declared criteria")
    lines += ["DECLARED CONVERGENCE CRITERIA", THIN]
    for k, v in criteria.items():
        lines.append(f"  {k:44s} {v}")
    lines.append("")
    for title, rows, chosen in blocks:
        lines += [THIN, title, THIN,
                  f"  {'N':>6s} {'evals':>8s} {'runtime':>8s} {'maxCIw':>8s} "
                  f"{'maxShift':>9s} {'rank==max':>10s} {'violations':>10s}"]
        for row in rows:
            lines.append(
                f"  {row.n_base:6d} {row.n_evaluations:8d} {row.runtime_s:8.2f} "
                f"{row.max_ci_width_dominant:8.4f} "
                f"{(row.max_abs_shift_vs_largest or 0):9.4f} "
                f"{str(row.ranking_matches_largest):>10s} "
                f"{len(row.result.violations()):10d}"
            )
        lines.append(f"  chosen: N={chosen.n_base}" if chosen else
                     "  chosen: NONE met the criteria at any tested size")
        if chosen:
            lines.append(f"  {'param':28s} {'S1':>8s} {'S1 95% CI':>20s} "
                         f"{'ST':>8s} {'ST 95% CI':>20s}")
            for name, s1, st in chosen.result.ranked():
                lines.append(
                    f"  {name:28s} {s1.value:8.4f} [{s1.ci_low:+8.4f},{s1.ci_high:+8.4f}] "
                    f"{st.value:8.4f} [{st.ci_low:+8.4f},{st.ci_high:+8.4f}]"
                )
        lines.append("")
    return "\n".join(lines)


def sensitivity(blocks, mode_descriptions, validation_passed: bool, seed: int) -> str:
    lines = header(
        "GLOBAL SENSITIVITY (SOBOL)",
        "total-order ST and first-order S1 with bootstrap 95% confidence intervals",
        seed=seed,
    )
    if not validation_passed:
        lines += ["!! THE IMPLEMENTATION VALIDATION DID NOT PASS. "
                  "These results must not be used. !!", ""]
    lines += ["SENSITIVITY MODES", THIN]
    for mode, desc in mode_descriptions.items():
        lines.append(f"  {mode:24s} {desc}")
    lines.append("")

    for block in blocks:
        lines += [RULE,
                  f"{block['archetype_label']}   [{block['archetype_kind']}]",
                  f"  provenance: {block['provenance']}", RULE]
        if block.get("archetype_notes"):
            lines.append(f"  note: {block['archetype_notes']}")
        for mode, results in block["modes"].items():
            lines.append(f"\n  MODE {mode}")
            for res in results:
                lines.append(
                    f"    {res.output}   (N={res.n_base}, {res.n_evaluations} evaluations, "
                    f"dropped={res.dropped_rows})"
                )
                lines.append(f"      {'parameter':28s} {'S1':>8s} {'S1 95% CI':>20s} "
                             f"{'ST':>8s} {'ST 95% CI':>20s}")
                for name, s1, st in res.ranked():
                    lines.append(
                        f"      {name:28s} {s1.value:8.4f} "
                        f"[{s1.ci_low:+8.4f},{s1.ci_high:+8.4f}] {st.value:8.4f} "
                        f"[{st.ci_low:+8.4f},{st.ci_high:+8.4f}]"
                    )
                if res.violations():
                    lines.append(f"      VIOLATIONS: {res.violations()}")
        lines.append("")
    return "\n".join(lines)


