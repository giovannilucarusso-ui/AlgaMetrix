def gwp_harmonization(p, conclusion_lines, class_disagreements) -> str:
    lines = header(
        "GWP ANALYSIS POPULATIONS",
        "published evidence, engine reproductions of published evidence, and "
        "model-derived extensions - kept apart",
    )

    lines += [RULE, "PUBLISHED GWP LITERATURE SET", RULE,
              f"  n = {p.n_published}", ""]
    lines.append(format_spread(p.published_spread_net, "kg CO2-eq/kg"))
    lines += ["", "  by analysis class:"]
    for cls, ids in sorted(p.published_by_class.items()):
        lines.append(f"    {cls:44s} n={len(ids):2d}  {', '.join(ids)}")
    lines.append("")
    lines += [f"  {'study_id':26s} {'published GWP':>13s}  system"]
    for r in p.published_literature:
        lines.append(
            f"  {r.study_id:26s} {fmt(r.reported_gwp):>13s}  "
            f"{fmt(r.cultivation_system)}"
        )
    lines.append("")

    lines += [RULE, "GWP-REPRODUCED MATCHED SET", RULE,
              "  Only studies with an actual published GWP endpoint that the engine can "
              "execute.",
              f"  n = {p.n_reproduced}", ""]
    if p.blocked:
        lines += ["  BLOCKED - published GWP, declared Tier B, not executable:"]
        for sid, why in sorted(p.blocked.items()):
            lines.append(f"    {sid:26s} {why}")
        lines.append("")
    if p.reproduced_cases:
        lines.append(_case_table(p.reproduced_cases))
        lines.append("")
        for sp in (p.reproduced_spread_native_gross, p.reproduced_spread_common_gross):
            if sp is not None:
                lines.append(format_spread(sp, "kg CO2-eq/kg"))
                lines.append("")
    else:
        lines += ["  No case in this set.", ""]

    lines += [RULE, "FULL EXECUTABLE FOREGROUND SET", RULE,
              "  Every scenario the engine can run. Cases labelled "
              "'model_derived_gwp_from_tea_scenario'",
              "  come from studies that published no GWP: they are model output, not "
              "validation.",
              f"  n = {len(p.executable_cases)}", ""]
    lines.append(_case_table(p.executable_cases))
    lines.append("")
    lines += [f"  common background applied: {p.background.name} "
              f"(elec {p.background.elec_gwp:g} kg CO2-eq/kWh, "
              f"heat {p.background.heat_gwp:g} kg CO2-eq/MJ; {p.background.source})", ""]
    for sp in (p.executable_spread_native_gross, p.executable_spread_common_gross,
               p.executable_spread_native_net, p.executable_spread_common_net):
        lines.append(format_spread(sp, "kg CO2-eq/kg"))
        lines.append("")

    if class_disagreements:
        lines += ["  DECLARED vs RULE-DERIVED ANALYSIS CLASS", THIN]
        for sid, declared, rule in class_disagreements:
            lines.append(f"    {sid:26s} declared={declared}  rule={rule}")
        lines.append("")

    lines += [RULE, "CONCLUSION (auto-generated, conditional)", RULE]
    for c in conclusion_lines:
        lines.append("  " + c)
    lines.append("")
    return "\n".join(lines)


def _case_table(cases) -> str:
    head = (
        f"  {'study_id':24s} {'analysis class':38s} {'elec':>7s} "
        f"{'nat.CF':>7s} {'com.CF':>7s} {'grossN':>8s} {'adjN':>8s} {'netN':>8s} "
        f"{'grossC':>8s} {'netC':>8s} {'publ.':>7s}"
    )
    rows = [head, "  " + THIN]
    for c in cases:
        rows.append(
            f"  {c.study_id:24s} {c.analysis_class:38s} {c.elec_kwh_per_kg:7.2f} "
            f"{c.native_elec_gwp:7.3f} {c.common_elec_gwp:7.3f} "
            f"{c.native_gross:8.3f} {c.native_adjustment:8.3f} {c.native_net:8.3f} "
            f"{c.common_gross:8.3f} {c.common_net:8.3f} "
            f"{(f'{c.published_gwp:.2f}' if c.published_gwp is not None else '-'):>7s}"
        )
    rows.append("  (N = native background, C = common background; adj = biogenic-carbon "
                "adjustment)")
    for c in cases:
        for n in c.notes:
            rows.append(f"    [{c.study_id}] {n}")
    return "\n".join(rows)


