def study_selection_audit(dataset, tier_disagreements) -> str:
    meta = dataset.meta
    lines = header(
        "STUDY SELECTION AND DATA-EXTRACTION AUDIT",
        f"dataset version {meta.get('dataset_version', 'unknown')} "
        f"({len(dataset)} records)",
    )

    lines += [
        "1. HOW THE EVIDENCE SET WAS ASSEMBLED",
        THIN,
        f"  systematic search claimed : {fmt(meta.get('is_systematic_search'))}",
        f"  search sources            : {fmt(meta.get('search_sources'))}",
        f"  search period             : {fmt(meta.get('search_period'))}",
        f"  search strings            : {fmt(meta.get('search_strings'))}",
        f"  date compiled             : {fmt(meta.get('date_compiled'))}",
        "",
        "  This is a CURATED EVIDENCE SET, not a systematic review. The identification",
        "  and screening process was not recorded when the dataset was assembled, so a",
        "  PRISMA-style flow of identified / screened / included / excluded counts",
        "  cannot be reported. The counts below describe the dataset as it now stands,",
        "  which is not the same thing.",
        "",
        "2. FLOW (what is genuinely known)",
        THIN,
    ]
    n = len(dataset)
    n_cost = sum(1 for r in dataset if r.has_cost)
    n_gwp = sum(1 for r in dataset if r.has_published_gwp)
    n_b = sum(1 for r in dataset if r.reconstructability_tier == "B")
    n_exec = sum(1 for r in dataset if r.is_executable)
    lines += [
        f"  records in dataset                    : {n}",
        f"  identified / screened / excluded before inclusion : unknown (not recorded)",
        f"  reporting an economic value           : {n_cost}",
        f"  reporting a published GWP endpoint    : {n_gwp}",
        f"  declared Tier B                       : {n_b}",
        f"  executable by the engine today        : {n_exec}",
        "",
        "3. TIER RULE AND DISAGREEMENTS",
        THIN,
        "  Tier B requires ALL of: a published foreground inventory, published CAPEX or",
        "  OPEX information, and a scenario builder registered in",
        "  paper/reconstructions.py. Anything else is Tier A - a literature point that",
        "  may enter descriptive statistics but not a mechanistic reconstruction.",
        "",
    ]
    if tier_disagreements:
        lines.append("  Studies whose declared tier is not supported by the evidence:")
        for sid, declared, rule in tier_disagreements:
            lines.append(f"    {sid:26s} declared={declared}  rule={rule}")
        lines.append("")
    else:
        lines.append("  No disagreement between declared tier and the rule.\n")

    lines += [
        "4. EVIDENCE CLASS AND DECLARED DEPENDENCIES",
        THIN,
        "  What each comparison DEPENDS ON, not how well it did. None of these records",
        "  is a prospective validation: every target was published before its scenario",
        "  was built, which is why no class is called 'blind'. Records sharing an",
        "  independence group are several scenarios of ONE publication, facility model",
        "  and author group.",
        "",
        f"  {'study_id':26s} {'evidence class':22s} {'overlap':>7s}  independence group",
    ]
    for r in sorted(dataset, key=lambda r: r.study_id):
        if (r.evidence_class or "none") == "none":
            continue
        lines.append(
            f"  {r.study_id:26s} {fmt(r.evidence_class):22s} "
            f"{fmt(r.author_overlap_with_algametrix):>7s}  {independence_key(r)}"
        )
    lines.append("")
    shared = {}
    for r in dataset:
        if (r.evidence_class or "none") != "none":
            shared.setdefault(independence_key(r), []).append(r.study_id)
    multi = {k: v for k, v in shared.items() if len(v) > 1}
    if multi:
        lines.append("  Groups contributing more than one comparison - counted as one source:")
        for key, ids in sorted(multi.items()):
            lines.append(f"    {key:36s} {', '.join(sorted(ids))}")
        lines.append("")
    any_dep = False
    for r in sorted(dataset, key=lambda r: r.study_id):
        for d in r.dependency_notes:
            any_dep = True
            lines.append(f"  [{r.study_id}] {d}")
    if not any_dep:
        lines.append("  no dependency recorded on any record")
    lines.append("")

    lines += ["5. PER-STUDY RECORD", THIN,
              f"  {'study_id':26s} {'tier':4s} {'compl.':>7s}  {'exec':>5s}  citation"]
    for r in sorted(dataset, key=lambda r: r.study_id):
        lines.append(
            f"  {r.study_id:26s} {fmt(r.reconstructability_tier):4s} "
            f"{r.completeness():7.0%}  {'yes' if r.is_executable else 'no':>5s}  "
            f"{r.full_citation[:60]}"
        )
    lines.append("")

    lines += ["6. PROVENANCE AND TRACEABILITY GAPS", THIN,
              "  Provenance (identified source) is REQUIRED to enter any main result.",
              "  Traceability (DOI and the value's location inside the source) is not",
              "  required, but every gap is listed so it is visible.",
              ""]
    any_gap = False
    for r in sorted(dataset, key=lambda r: r.study_id):
        gaps = r.missing_provenance()
        if gaps:
            any_gap = True
            lines.append(f"  {r.study_id:26s} NO PROVENANCE: missing {', '.join(gaps)}")
    if not any_gap:
        lines.append("  provenance: complete for every record")
    n_trace = 0
    for r in sorted(dataset, key=lambda r: r.study_id):
        gaps = r.missing_traceability()
        if gaps:
            n_trace += 1
            lines.append(f"  {r.study_id:26s} traceability gap: {', '.join(gaps)}")
    lines += [f"  {n_trace} of {len(dataset)} records lack full traceability metadata.", ""]

    lines += ["7. OPEN TODOs FROM MISSING SOURCE INFORMATION", THIN]
    total = 0
    for r in sorted(dataset, key=lambda r: r.study_id):
        for t in r.todos:
            total += 1
            lines.append(f"  [{r.study_id}] {t}")
    if not total:
        lines.append("  none")
    lines += ["", f"  total open TODOs: {total}", ""]
    return "\n".join(lines)


