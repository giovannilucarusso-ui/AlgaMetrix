def _definition_audit_block(defn, indent: str = "  ") -> list[str]:
    """How far the cohort's homogeneity is verified rather than merely declared."""
    from .endpoints import ENDPOINT_DEFINITION_FIELDS

    lines = [
        "ENDPOINT-DEFINITION COMPLETENESS OF THE COHORT",
        THIN,
        f"{indent}Screening on endpoint type and functional unit makes the cohort uniform in",
        f"{indent}its LABEL. Whether the underlying numbers are the same quantity depends on",
        f"{indent}the attributes below, study by study.",
        "",
        f"{indent}{'attribute':30s} {'known':>8s} {'unknown':>8s}",
    ]
    for f in ENDPOINT_DEFINITION_FIELDS:
        k = defn.known.get(f, 0)
        lines.append(f"{indent}{f:30s} {k:8d} {defn.n - k:8d}")
    lines += ["", f"{indent}{'study_id':26s} attributes still unknown"]
    for sid, missing in sorted(defn.unknown_by_study.items()):
        lines.append(f"{indent}{sid:26s} {', '.join(missing) if missing else '(none)'}")
    lines += ["", f"{indent}VERDICT"]
    for s in defn.statement():
        lines.append(f"{indent}  {s}")
    lines.append("")
    return lines


def economic_endpoint_audit(dataset, audits, breakdown, primary_definition,
                            definition=None) -> str:
    lines = header(
        "ECONOMIC ENDPOINT AUDIT",
        "which economic quantity each study reports, and whether it may enter the "
        "primary production-cost comparison",
    )
    lines += ["PRIMARY ENDPOINT", THIN, f"  {primary_definition}", ""]

    lines += ["LITERATURE STATISTICS BY ENDPOINT TYPE (not pooled)", THIN]
    for etype, ids in sorted(breakdown.items()):
        lines.append(f"  {etype:32s} n={len(ids):2d}  {', '.join(ids)}")
    lines.append("")

    lines += [
        "PER-STUDY CLASSIFICATION",
        THIN,
        f"  {'study_id':26s} {'source metric':28s} {'classification':30s} "
        f"{'eligible':8s} reason",
    ]
    for a in audits:
        lines.append(
            f"  {a.study_id:26s} {(a.source_metric or 'unknown')[:28]:28s} "
            f"{a.classification:30s} {'yes' if a.eligible else 'NO':8s} "
            f"{a.exclusion_reason or ''}"
        )
    lines.append("")

    lines += ["CAVEATS ON INCLUDED STUDIES (endpoint definition not fully verified)", THIN]
    any_caveat = False
    for a in audits:
        if a.eligible and a.caveats:
            any_caveat = True
            lines.append(f"  {a.study_id:26s} {'; '.join(a.caveats)}")
    if not any_caveat:
        lines.append("  none")
    lines.append("")

    if definition is not None:
        lines += _definition_audit_block(definition)

    n_elig = sum(1 for a in audits if a.eligible)
    lines += [
        "SUMMARY",
        THIN,
        f"  studies with an economic value : {sum(1 for a in audits if a.source_metric)}",
        f"  eligible for the primary spread: {n_elig}",
        f"  excluded                       : {sum(1 for a in audits if not a.eligible)}",
        "",
    ]
    return "\n".join(lines)


