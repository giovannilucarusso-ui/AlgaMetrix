"""Writers for the ``results/*.txt`` files.

Every file states, at the top, what produced it and under which conventions, so
a number lifted into the manuscript carries its own audit trail.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date

from . import reproduction
from .schema import fmt, independence_key
from .stats import Spread, format_spread

RULE = "=" * 78
THIN = "-" * 78


def _wrap(text: str, width: int) -> list[str]:
    """Wrap a paragraph, collapsing the newlines a YAML block scalar leaves behind."""
    import textwrap

    return textwrap.wrap(" ".join(str(text).split()), width=width) or [""]


def header(title: str, subtitle: str = "", seed: int | None = None) -> list[str]:
    lines = [title, RULE]
    if subtitle:
        lines.append(subtitle)
    lines.append(f"generated by reproduce.py on {date.today().isoformat()}"
                 + (f"; seed={seed}" if seed is not None else ""))
    lines.append("")
    return lines


